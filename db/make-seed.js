'use strict';
// Regenerates db/seed.sql from data/games/sample-football.json. No packages.
// Run from the repository root:  node db/make-seed.js
// It replays the game through js/rules.js to get each play's text, score and fantasy points.
var fs = require('fs');
var path = require('path');
var root = path.join(__dirname, '..');
var Rules = require(path.join(root, 'js', 'rules.js'));
var file = JSON.parse(fs.readFileSync(path.join(root, 'data', 'games', 'sample-football.json'), 'utf8'));

var GAME_ID = 'sample-football';
var START = Date.parse('2026-11-15T18:00:00Z'); // an invented kickoff time
var SPAN_MS = 3 * 60 * 60 * 1000;               // plays are spread evenly over three hours

function q(v) { return v === null || v === undefined ? 'NULL' : "'" + String(v).replace(/'/g, "''") + "'"; }
function n(v) { return v === null || v === undefined ? 'NULL' : String(v); }
function j(v) { return q(JSON.stringify(v)) + '::jsonb'; }

var teams = file.teams;
var steps = Rules.flatten(file.game, teams);
var state = Rules.create(teams);
var plays = [];
var half = 1;
steps.forEach(function (st) {
  if (st.kind === 'half') { Rules.startHalf(state); half = 2; return; }
  if (st.kind === 'final') return;
  var r = Rules.apply(state, st.e, st.team);
  plays.push({ st: st, r: r, half: half, score: state.score.slice() });
});

// The game file has no clock, so quarters are worked out: each half is split in two by play count.
[1, 2].forEach(function (h) {
  var inHalf = plays.filter(function (p) { return p.half === h; });
  var cut = Math.ceil(inHalf.length / 2);
  inHalf.forEach(function (p, i) { p.quarter = (h - 1) * 2 + (i < cut ? 1 : 2); });
});

var out = [];
out.push('-- Generated by db/make-seed.js from data/games/sample-football.json. Do not edit by hand.');
out.push('-- INVENTED sample game. Quarters and times are worked out, not in the game file.');
out.push('-- Safe to run twice: rows that already exist are skipped.');
out.push('BEGIN;');
out.push('');
out.push('INSERT INTO games (id, sport, home, away, created_at, final_home, final_away) VALUES (' +
  [q(GAME_ID), q('football'), q(teams[0].id), q(teams[1].id), q(new Date(START).toISOString()), n(state.score[0]), n(state.score[1])].join(', ') +
  ') ON CONFLICT (id) DO NOTHING;');
out.push('');
out.push('INSERT INTO plays (game_id, seq, played_at, quarter, team, slot, player, kind, yards, fantasy_points, detail, why) VALUES');

var rows = plays.map(function (p, i) {
  var e = p.st.e, r = p.r;
  var at = new Date(START + Math.round(i * SPAN_MS / plays.length)).toISOString();
  // One row per play. The row is credited to the player with the biggest fantasy move on that play;
  // every fantasy entry of the play is kept in detail.fp.
  var fp = r.fp || [];
  var main = null;
  fp.forEach(function (f) { if (!main || Math.abs(f.pts) > Math.abs(main.pts)) main = f; });
  var team = teams[p.st.team].id, slot = null, player = null, pts = 0;
  if (main) {
    team = teams[main.team].id; slot = main.role; pts = main.pts;
    player = main.role === 'DST' ? team + ' defense' : teams[main.team].roster[main.role] || null;
  } else if (typeof (e.by || e.to) === 'string') {
    slot = e.by || e.to;
    player = teams[p.st.team].roster[slot] || null;
  }
  var yards = e.yds !== undefined ? e.yds : (e.net !== undefined ? e.net : null);
  var detail = {
    event: e, text: r.text, score_after: p.score, drive: p.st.drive + 1,
    fp: fp.map(function (f) { return { team: teams[f.team].id, slot: f.role, pts: f.pts }; })
  };
  var why = e.why || {};
  return '  (' + [q(GAME_ID), n(i + 1), q(at), n(p.quarter), q(team), q(slot), q(player), q(e.t), n(yards), n(pts), j(detail), j(why)].join(', ') + ')';
});
out.push(rows.join(',\n'));
out.push('ON CONFLICT DO NOTHING;');
out.push('');
out.push('COMMIT;');
out.push('');
fs.writeFileSync(path.join(__dirname, 'seed.sql'), out.join('\n'));
console.log('wrote db/seed.sql: 1 game, ' + plays.length + ' plays, final ' + teams[0].id + ' ' + state.score[0] + ', ' + teams[1].id + ' ' + state.score[1]);

'use strict';
// Regenerates db/seed.sql from data/games/sample-football.json. No packages.
// Run from the repository root:  node db/make-seed.js
// The game is replayed by server/replay.js (the same code push-game.js uses).
var fs = require('fs');
var path = require('path');
var root = path.join(__dirname, '..');
var g = require(path.join(root, 'server', 'replay.js')).buildPlays(path.join(root, 'data', 'games', 'sample-football.json'));

function q(v) { return v === null || v === undefined ? 'NULL' : "'" + String(v).replace(/'/g, "''") + "'"; }
function n(v) { return v === null || v === undefined ? 'NULL' : String(v); }
function j(v) { return q(JSON.stringify(v)) + '::jsonb'; }

var out = [];
out.push('-- Generated by db/make-seed.js from data/games/sample-football.json. Do not edit by hand.');
out.push('-- INVENTED sample game. Quarters and times are worked out, not in the game file.');
out.push('-- Safe to run twice: rows that already exist are skipped.');
out.push('BEGIN;');
out.push('');
out.push('INSERT INTO games (id, sport, home, away, created_at, final_home, final_away) VALUES (' +
  [q(g.id), q(g.sport), q(g.home), q(g.away), q(g.started_at), n(g.final[0]), n(g.final[1])].join(', ') +
  ') ON CONFLICT (id) DO NOTHING;');
out.push('');
out.push('INSERT INTO plays (game_id, seq, played_at, quarter, team, slot, player, kind, yards, fantasy_points, detail, why) VALUES');
out.push(g.plays.map(function (p) {
  return '  (' + [q(g.id), n(p.seq), q(p.played_at), n(p.quarter), q(p.team), q(p.slot), q(p.player), q(p.kind), n(p.yards),
    n(p.fantasy_points), j(p.detail), j(p.why)].join(', ') + ')';
}).join(',\n'));
out.push('ON CONFLICT DO NOTHING;');
out.push('');
out.push('COMMIT;');
out.push('');
fs.writeFileSync(path.join(__dirname, 'seed.sql'), out.join('\n'));
console.log('wrote db/seed.sql: 1 game, ' + g.plays.length + ' plays, final ' + g.home + ' ' + g.final[0] + ', ' + g.away + ' ' + g.final[1]);
